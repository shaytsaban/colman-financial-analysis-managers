def _two_years(head):
    d, g, fmt, sty = {'A1': 'שורה בדוח', 'B1': 'שנת 2026', 'C1': 'שנת 2027', 'D1': head[0], 'E1': head[1]}, {}, {}, {}
    for c in 'ABCDE': sty[f'{c}1'] = {'fill': '#e1e7f8', 'b': True}
    for i, (n, a, b) in enumerate(_HL):
        r = 2 + i; d[f'A{r}'] = n; g[f'B{r}'] = a; g[f'C{r}'] = b; fmt[f'B{r}'] = fmt[f'C{r}'] = 'acc0'
    return d, g, fmt, sty


