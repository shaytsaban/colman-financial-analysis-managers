def ROWS3(rows, start=1):
    """A table with a label and three amount columns, revealed row by row. rows: (label, a, b, c, total?)."""
    out, n = '', start
    for lab, a, b, c, tot in rows:
        cell = lambda x: f'<td class="amt">{x if str(x).startswith("<") else TX(str(x))}</td>'
        out += ST(n, f'<td>{TX(lab)}</td>' + cell(a) + cell(b) + cell(c), 'tr', 'tot' if tot else '')
        n += 1
    return out, n


