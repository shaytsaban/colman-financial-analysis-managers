def _node(i, ic, h, t, ph, pb):
    inner = f'<span class="pi">{ic}</span><b>{TX(h)}</b><span class="pt">{TX(t)}</span>'
    if MODE == 'pdf':
        return f'<div class="card"><b>{i + 1}. {TX(h)}</b>: {TX(t)}. {pb}</div>'
    arrow = '<i class="par">←</i>' if i else ''
    return ST(i + 1, f'{arrow}<button class="morebtn pnode" type="button">{inner}</button><div class="more-c" hidden><div class="more-h">{TX(ph)}</div>{pb}</div>', cls='pn')


